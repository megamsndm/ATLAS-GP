// ─────────────────────────────────────────────────────────────────────────────
// Lorentz-Berthelot combining rules for heteroatomic LJ
// ─────────────────────────────────────────────────────────────────────────────
inline double lb_sigma  (double si, double sj) { return 0.5*(si+sj); }
inline double lb_epsilon(double ei, double ej) { return std::sqrt(ei*ej); }

// ─────────────────────────────────────────────────────────────────────────────
// Abstract Potential base class
// ─────────────────────────────────────────────────────────────────────────────
struct Potential {
    virtual ~Potential() = default;

    // Compute energy AND gradient (grad must be pre-zeroed, size 3N)
    virtual double energy_gradient(const System& sys, double* grad) const = 0;

    // Compute energy only (faster, no gradient)
    virtual double energy_only(const System& sys) const = 0;

    // Mean sigma — used for sphere radius and bond cutoff scaling
    virtual double get_mean_sigma(const System& sys) const = 0;

    // Human-readable name
    virtual std::string name() const = 0;

    // Check if this potential supports the given system
    virtual void validate(const System& sys) const {}
};

// ─────────────────────────────────────────────────────────────────────────────
// Factory: create potential by name
// ─────────────────────────────────────────────────────────────────────────────
// Forward declarations — implemented in concrete potential headers
std::unique_ptr<Potential> make_potential(const std::string& name, const System& sys);
